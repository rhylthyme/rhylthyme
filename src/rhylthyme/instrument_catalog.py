#!/usr/bin/env python3
"""
Instrument Catalog Module

Provides a browsable taxonomy of instrument types organized by category,
with defaults for resource constraints. This is the "type-level" layer
between coarse environment types (kitchen, laboratory) and specific
physical equipment instances (ResourceSpecification).

Each instrument type provides sensible defaults for maxConcurrent,
actorsRequired, and suggested actor types, making it easy to build
environment resource constraints from the catalog.
"""

from dataclasses import asdict, dataclass, field
from typing import Dict, List, Optional


@dataclass
class InstrumentType:
    """A type of instrument/equipment with default resource constraint values."""

    instrument_id: str
    name: str
    description: str
    category_id: str
    default_task_name: str
    default_max_concurrent: int
    default_actors_required: float
    suggested_qualified_actor_types: List[str] = field(default_factory=list)
    typical_specs: Dict[str, str] = field(default_factory=dict)
    environment_types: List[str] = field(default_factory=list)
    tags: List[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    def to_resource_constraint(
        self,
        max_concurrent: Optional[int] = None,
        actors_required: Optional[float] = None,
        qualified_actor_types: Optional[List[str]] = None,
        description: Optional[str] = None,
    ) -> dict:
        """Convert to a standard resourceConstraints entry."""
        rc = {
            "task": self.default_task_name,
            "maxConcurrent": (
                max_concurrent
                if max_concurrent is not None
                else self.default_max_concurrent
            ),
            "description": description or self.description,
        }
        ar = (
            actors_required
            if actors_required is not None
            else self.default_actors_required
        )
        if ar > 0:
            rc["actorsRequired"] = ar
        qat = qualified_actor_types or self.suggested_qualified_actor_types
        if qat:
            rc["qualifiedActorTypes"] = qat
        return rc


@dataclass
class InstrumentCategory:
    """A category grouping related instrument types."""

    category_id: str
    name: str
    description: str
    icon: str
    environment_types: List[str] = field(default_factory=list)
    instruments: List[InstrumentType] = field(default_factory=list)

    def to_dict(self, include_instruments: bool = True) -> dict:
        d: Dict[str, object] = {
            "category_id": self.category_id,
            "name": self.name,
            "description": self.description,
            "icon": self.icon,
            "environment_types": self.environment_types,
        }
        if include_instruments:
            d["instruments"] = [i.to_dict() for i in self.instruments]
        return d


