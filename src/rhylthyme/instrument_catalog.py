def get_catalog_for_environment_type(env_type: str) -> List[InstrumentCategory]:
    """Return catalog categories that include the given environment type."""
    results = []
    for cat in INSTRUMENT_CATALOG.values():
        if env_type in cat.environment_types:
            results.append(cat)
    return results


def get_category(category_id: str) -> Optional[InstrumentCategory]:
    """Return a single category by ID."""
    return INSTRUMENT_CATALOG.get(category_id)


def get_instrument(instrument_id: str) -> Optional[InstrumentType]:
    """Find an instrument type by its ID across all categories."""
    for cat in INSTRUMENT_CATALOG.values():
        for inst in cat.instruments:
            if inst.instrument_id == instrument_id:
                return inst
    return None


def search_instruments(
    query: str, env_type: Optional[str] = None
) -> List[InstrumentType]:
    """Search instruments by name, description, tags, or task name."""
    q = query.lower()
    results = []
    for cat in INSTRUMENT_CATALOG.values():
        if env_type and env_type not in cat.environment_types:
            continue
        for inst in cat.instruments:
            if (
                q in inst.name.lower()
                or q in inst.description.lower()
                or q in inst.default_task_name.lower()
                or any(q in t for t in inst.tags)
            ):
                results.append(inst)
    return results


def instrument_to_resource_constraint(
    instrument_id: str,
    max_concurrent: Optional[int] = None,
    actors_required: Optional[float] = None,
    qualified_actor_types: Optional[List[str]] = None,
    description: Optional[str] = None,
) -> Optional[dict]:
    """Convert an instrument type to a resourceConstraints entry."""
    inst = get_instrument(instrument_id)
    if not inst:
        return None
    return inst.to_resource_constraint(
        max_concurrent, actors_required, qualified_actor_types, description
    )


def get_catalog_summary() -> dict:
    """Return a summary dict suitable for API responses."""
    return {
        "categories": [cat.to_dict() for cat in INSTRUMENT_CATALOG.values()],
        "total_categories": len(INSTRUMENT_CATALOG),
        "total_instruments": sum(
            len(cat.instruments) for cat in INSTRUMENT_CATALOG.values()
        ),
    }
